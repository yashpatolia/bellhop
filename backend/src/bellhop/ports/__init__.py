"""Ports: the only interfaces services depend on. Adapters implement them.

All ports are synchronous Protocols. Swap implementations (in-memory, SpacetimeDB, Moss)
at the composition root (`bellhop.container`), never inside services.
"""

from __future__ import annotations

from collections.abc import Callable
from datetime import datetime
from typing import Any, Protocol

from bellhop.domain import Alert, Call, MemoryFact, Nurse, Resident, Robot, Visit


class CallRepository(Protocol):
    def save(self, call: Call) -> None: ...
    def get(self, call_id: str) -> Call | None: ...
    def list_open(self) -> list[Call]: ...
    def list_all(self) -> list[Call]: ...


class ResidentRepository(Protocol):
    def save(self, resident: Resident) -> None: ...
    def get(self, resident_id: str) -> Resident | None: ...
    def by_room(self, room: str) -> Resident | None: ...
    def list_all(self) -> list[Resident]: ...


class NurseRepository(Protocol):
    def save(self, nurse: Nurse) -> None: ...
    def get(self, nurse_id: str) -> Nurse | None: ...
    def list_on_shift(self) -> list[Nurse]: ...
    def list_all(self) -> list[Nurse]: ...


class RobotRepository(Protocol):
    def save(self, robot: Robot) -> None: ...
    def get(self, robot_id: str) -> Robot | None: ...
    def list_all(self) -> list[Robot]: ...


class VisitRepository(Protocol):
    def save(self, visit: Visit) -> None: ...
    def for_call(self, call_id: str) -> Visit | None: ...
    def list_all(self) -> list[Visit]: ...


class AlertRepository(Protocol):
    def save(self, alert: Alert) -> None: ...
    def get(self, alert_id: str) -> Alert | None: ...
    def list_all(self) -> list[Alert]: ...
    def for_call(self, call_id: str) -> list[Alert]: ...


class MemoryIndex(Protocol):
    """Semantic recall over resident notes. Must answer in <50 ms for the voice loop."""

    def add(self, fact: MemoryFact) -> None: ...
    def recall(self, resident_id: str, utterance: str, k: int = 3) -> list[MemoryFact]: ...


class Notifier(Protocol):
    """Delivers an alert to a human (dashboard banner, phone push, ...)."""

    def send(self, alert: Alert) -> None: ...


class RobotGateway(Protocol):
    """Commands to the robot (Jeremy's side). Status flows back through RobotRepository."""

    def go_to(self, robot_id: str, room: str) -> None: ...
    def follow_marker(self, robot_id: str, marker: str) -> None: ...
    def set_led(self, robot_id: str, state: str) -> None: ...
    def stop(self, robot_id: str) -> None: ...


Handler = Callable[[Any], None]


class EventBus(Protocol):
    def publish(self, event: Any) -> None: ...
    def subscribe(self, event_type: type, handler: Handler) -> None: ...


class Clock(Protocol):
    def now(self) -> datetime: ...


class IdGenerator(Protocol):
    def new_id(self, prefix: str) -> str: ...
